fruits = ["apple", "banana"]
print("Исходный список:", fruits)

# 1. Добавьте "orange" в конец списка
fruits.append("orange")
print("После добавления 'orange':", fruits)

# 2. Вставьте "grape" по индексу 1
fruits.insert(1, "grape")
print("После вставки 'grape' по индексу 1:", fruits)

# 3. Удалите "banana"
fruits.remove("banana")
print("После удаления 'banana':", fruits)

# 4. Отсортируйте список
fruits.sort()
print("После сортировки:", fruits)

# 5. Переверните список
fruits.reverse()
print("После переворота:", fruits)